/* projectionOn2DRollingCone against the optimality conditions of the
   projection p of x on K = {|r_t| <= mu r_n, |r_r| <= mu_r r_n}, the cone
   generated by g = (1, +-mu, +-mu_r): p in K, x - p in the polar cone
   (g . (x - p) <= 0 for the four generators), p . (x - p) = 0. */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

#include "projectionOnRollingCone.h"
#include "rfc2d_test_tools.h"

int main(void) {
  const double mus[] = {0., 0.1, 0.5, 1., 3.};
  const double murs[] = {0., 0.01, 0.1, 0.5, 2.};
  const double scales[] = {1e-3, 1., 1e3};
  srand(1);
  double worst = 0.;
  int unprojected = 0;
  const int n = 50000;
  for (int k = 0; k < n; ++k) {
    double mu = mus[rand() % 5], mur = murs[rand() % 5], s = scales[rand() % 3];
    double x[3], p[3];
    for (int i = 0; i < 3; ++i) p[i] = x[i] = s * rfc2d_urand(-1., 1.);
    unsigned int status = projectionOn2DRollingCone(p, mu, mur);
    if (status == 20) unprojected++;
    double d[3] = {x[0] - p[0], x[1] - p[1], x[2] - p[2]};
    double scale = fmax(1e-300, sqrt(x[0] * x[0] + x[1] * x[1] + x[2] * x[2]));
    double v = 0.;
    v = fmax(v, (fabs(p[1]) - mu * p[0]) / scale);
    v = fmax(v, (fabs(p[2]) - mur * p[0]) / scale);
    for (int a = -1; a <= 1; a += 2)
      for (int b = -1; b <= 1; b += 2)
        v = fmax(v, (d[0] + a * mu * d[1] + b * mur * d[2]) / scale);
    v = fmax(v, fabs(p[0] * d[0] + p[1] * d[1] + p[2] * d[2]) / (scale * scale));
    worst = fmax(worst, v);
  }
  printf("projectionOn2DRollingCone: %d cases, worst violation %.2e, unprojected %d\n", n,
         worst, unprojected);
  return (worst > 1e-12 || unprojected > 0) ? 1 : 0;
}
